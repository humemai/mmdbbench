# THE TWO LIMITS, as generated text under a table that prints the column.

def _join_and(items):
    """"a", "a and b", "a, b, and c": the page's serial comma (the same as export_web._join_and)."""
    items = list(items)
    if len(items) < 3:
        return " and ".join(items)
    return ", ".join(items[:-1]) + ", and " + items[-1]


def _peak(entry):
    stat = (entry.get("metrics") or {}).get(PEAK_LABEL)
    v = stat.get("median") if isinstance(stat, dict) else None
    return v if isinstance(v, (int, float)) else None


def second_size_engines(table):
    """(engines with a peak memory reading at a second size, engines with a small-size reading and none at a second size), by label, in the
    order the table prints them.

    A slope needs two sizes of the same engine, so it is read per engine, from the finished payload: the entries that carry a peak memory
    number (a censored entry carries a mark and no number), over the sizes the table prints. The second size may be any other size of the
    table: the large size of the pair or an extra size."""
    sizes_of, small, order = {}, [], []
    for e in table.get("entries") or []:
        if e.get("outcome") or _peak(e) is None:
            continue
        label = e.get("backend")
        sizes_of.setdefault(label, set()).add(str(e.get("size_id") or e.get("scale")))
        if label not in order:
            order.append(label)
        if e.get("size_class") == "small" and label not in small:
            small.append(label)
    both = [label for label in order if len(sizes_of[label]) >= 2 and label in small]
    only = [label for label in small if len(sizes_of[label]) < 2]
    return both, only


def notes(table) -> list:
    """The two generated sentences under a table that prints the per-million column, as (text, values) pairs; the values are the strings the
    generator put in the text (export_web registers them with `_gen`). Neither sentence has a number in it.

    Which engines of the table have a second size to read a slope from is read from its entries (second_size_engines), so the sentence names
    them from the payload and no lane or size is typed."""
    label = column_of(table)
    unit = unit_of(label) if label else None
    if not unit:
        return []
    first = (f"{label[0].upper() + label[1:]} is the peak memory GiB of the same row divided by the number of {unit} the table loads, counted "
             f"in millions. It is printed for the small size only: at every other size, and for a row that records no count of {unit}, the "
             f"cell is a dash. A small-size figure mixes the cost of the data with a fixed cost that does not depend on it (heap and cache "
             f"defaults, buffers allocated up front). Dividing by the number of {unit} spreads that fixed cost over few of them, so it "
             f"overstates the cost of one, most at the smallest sizes.")
    both, only = second_size_engines(table)
    if not both:
        which = "No engine on this table has one."
    elif not only:
        which = "Every engine on this table has one."
    else:
        which = f"Every engine on this table has one except {_join_and(only)}."
    second = (f"The reliable comparison is the slope between two sizes: the extra memory an engine holds at the larger size, divided by the "
              f"extra {unit}. A slope needs a second size with a peak memory reading for the same engine. {which} The column flags heavy "
              f"engines at the small size. It does not show how an engine behaves at scale: a failure at a large size, such as running out "
              f"of memory, is not a straight line from the small numbers.")
    return [(first, [label[0].upper() + label[1:], unit]), (second, [unit, *only])]
