"""Peak memory per million records on the small-size tables (humemai/mmdbbench#133, Decision 2, confirmed 2026-11-23).

A table that prints a `peak memory GiB` column and an ingest rate gets one more column beside the memory: the same peak memory, divided by the
number of records the table loads, per million. "Records" is what the table's own ingest-rate column counts (documents, vertices plus edges,
vectors, points), so nothing new is counted; RECORDS names the row fields, per table, and the one place where they differ from the rate column.

This module imports the standard library and `size_classes` only, like size_classes.py: the exporter refuses to load without its overlays, and
the tests of this column (and any gate that wants to ask which rows get a value) need the arithmetic and the sentences without that machinery.
export_web binds it as `_MPM` and does the wiring (the column in the table specs, the aggregation over repetitions, the sentences under a table).

What a reader gets, and what the page says about it (the sentences are built here, registered as generated by export_web):
  - the value is printed for the SMALL size only (size_classes.SIZE_CLASS); at the large and the extra sizes the cell is a dash, which the page
    already says is "the column does not apply to that row";
  - a row that records no count of records, or no peak memory, has a dash: nothing is estimated;
  - a small-size figure mixes the cost of the data with a fixed cost, so dividing by records overstates the cost per record, most at the
    smallest sizes (limit 1);
  - the reliable comparison is the slope between two sizes, which a table gives only when every engine has a peak memory reading at a second
    size; the tables that do are derived from the payload, not typed; the column flags heavy engines and does not prove how one behaves at scale
    (limit 2).
"""
from __future__ import annotations

import size_classes as _SC

PEAK_LABEL = "peak memory GiB"
COLUMN_PREFIX = "peak memory GiB per million "

# table id (the id of OCT_TABLE_METRICS, so the document lane's id) -> (what a record is, the row fields that add up to the table's records).
# The unit names the type the way the ingest-rate columns do ("ingest documents/s", "ingest vertices+edges/s", "ingest+index vectors/s",
# "ingest points/s"), and it ends the header: "peak memory GiB per million vectors".
#   - l1tpc: line items and parts, as `_rate(("n_lineitem", "n_part"), "build_s")`.
#   - l2: persons and KNOWS edges, as the rate column.
#   - l2olap: the table's one size is the FULL network, whose message half (`msg_vertices`, `msg_edges`) is most of what the cell loads. The
#     rate column of that table counted persons and KNOWS only until humemai/mmdbbench#140, which understated the records of the full network by about
#     a factor of ninety; both columns now count the four fields, beside a Size label that names 3.2M vertices and 13.8M edges. All four fields are
#     required, so a row without the message counts has a dash and not a quietly smaller count.
#   - e2: products and edges, as the rate column.
#   - l3d, l3s: `n_docs`, the vectors the lane loaded (`build_docs_per_s` is `n_docs / build_s`).
#   - l4: `n_points`, the points the lane parsed (`ingest_pts_per_s` is `n_points / ingest time`).
RECORDS = {
    "l1tpc": ("documents", ("n_lineitem", "n_part")),
    "l2": ("vertices+edges", ("n_persons_ingested", "n_edges_ingested")),
    "l2olap": ("vertices+edges", ("n_persons_ingested", "n_edges_ingested", "msg_vertices", "msg_edges")),
    "e2": ("vertices+edges", ("n_products", "n_edges")),
    "l3d": ("vectors", ("n_docs",)),
    "l3s": ("vectors", ("n_docs",)),
    "l4": ("points", ("n_points",)),
}


def _num(v):
    try:
        return None if v in (None, "") else float(v)
    except (TypeError, ValueError):
        return None


def column_label(table_id: str) -> str:
    """The column header of a table: the unit of its records ends it, so the unit of the memory (GiB) and of the count are both in it."""
    return COLUMN_PREFIX + RECORDS[table_id][0]


def unit_of(label: str) -> str | None:
    """The record unit named in a per-million header, or None when the label is not one."""
    return label[len(COLUMN_PREFIX):] if str(label).startswith(COLUMN_PREFIX) else None


def column_of(table) -> str | None:
    """The per-million column a finished table prints, or None."""
    return next((c for c in table.get("columns") or [] if unit_of(c)), None)


def records(row, fields) -> float | None:
    """The records of a row: the sum of `fields`, every one of them present. None when one is missing or blank, or the sum is not positive."""
    total = 0.0
    for field in fields:
        v = _num(row.get(field))
        if v is None:
            return None
        total += v
    return total if total > 0 else None


def mib_per_million(peak_mib, n_records) -> float | None:
    """MiB of peak memory per million records, or None for a missing peak, a missing count or a count that is not positive."""
    if peak_mib is None or n_records is None or n_records <= 0:
        return None
    return peak_mib / (n_records / 1_000_000)


def applies(row) -> bool:
    """True for a row of the SMALL size class (size_classes.row_size_class): the only rows that get a value. A row the table cannot place has none."""
    return _SC.row_size_class(row) == "small"


def row_value(row, peak_mib, fields) -> float | None:
    """The row's MiB per million records, or None: not a small-size row, no peak memory, or no count of records. Nothing is estimated."""
    if not applies(row):
        return None
    return mib_per_million(peak_mib, records(row, fields))


def scale_stat(stat, n_records) -> dict | None:
    """A peak memory statistic ({median, min, max, n}, in GiB) as GiB per million records, for a cell whose record count is one constant
    (the dense table's multipass overlay, whose files carry no count: the corpus size is the lane's own). None when there is no usable stat."""
    if not isinstance(stat, dict) or n_records is None or n_records <= 0:
        return None
    try:
        return {"median": round(stat["median"] / (n_records / 1_000_000), 4), "min": round(stat["min"] / (n_records / 1_000_000), 4),
                "max": round(stat["max"] / (n_records / 1_000_000), 4), "n": stat["n"]}
    except (KeyError, TypeError):
        return None


